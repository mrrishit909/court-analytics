"""Offline evaluation on court systems the demo never uses. Writes docs/evaluation.md.

    python -m ca.evaluate
"""
import pathlib
import random

import numpy as np

from . import engine, seed, train, world

SEEDS = range(300, 306)


def main():
    _, tm = seed.train()
    ys, ps, base_type, base_judge, raw_judge, truth_p, prose = [], [], [], [], [], [], []
    cover = [0, 0]
    sim, sim_base, km_err, naive_err = [], [], [], []
    for s in SEEDS:
        w = world.build(s, 6000)
        model, (counts, priors, _, _), index, _, hold = train.train(w)
        tr = [m for m in w["motions"] if m["decided"] < world.SPLIT]
        rate_type = {t: np.mean([m["granted"] for m in tr if m["type"] == t]) for t in world.MOTIONS}
        for i, x, y in hold:
            m = w["motions"][i]
            c = w["cases"][m["case"]]
            g, n = counts.get((c["judge"], m["type"]), (0, 0))
            post = engine.posterior(g, n, priors[m["type"]])
            est = engine.estimate(model, x, post["sd"], seed=i)
            ys.append(int(y))
            ps.append(est["probability"])
            base_type.append(rate_type[m["type"]])
            base_judge.append(post["rate"])
            raw_judge.append(g / n if n else rate_type[m["type"]])
            truth_p.append(m["p_true"])
            prose.append(c["pro_se"])
            cover[0] += est["low"] <= m["p_true"] <= est["high"]
            cover[1] += 1
        # similarity: do the nearest cases share the hidden fact pattern?
        r = random.Random(s)
        for k in r.sample(range(len(w["cases"])), 300):
            c = w["cases"][k]
            got = index.query(c["facts"], 10, exclude=k)
            sim.append(np.mean([w["cases"][i]["pattern"] == c["pattern"] and w["cases"][i]["suit"] == c["suit"] for i, _ in got]))
            same = [i for i, x in enumerate(w["cases"]) if x["suit"] == c["suit"] and i != k]
            sim_base.append(np.mean([w["cases"][i]["pattern"] == c["pattern"] for i in r.sample(same, 10)]))
        # time to resolution: median by suit, against the generator's uncensored durations
        for suit in world.PATTERNS:
            cs = [c for c in w["cases"] if c["suit"] == suit]
            dur = [((c["closed"] or world.DATA_CUT) - c["filed"]).days for c in cs]
            true_median = float(np.median([c["true_days"] for c in cs]))
            km_err.append(abs(engine.quantile(engine.kaplan_meier(dur, [c["closed"] is not None for c in cs])) - true_median) / true_median)
            naive_err.append(abs(float(np.median([d for d, c in zip(dur, cs) if c["closed"]])) - true_median) / true_median)
    ys, ps, prose = np.array(ys), np.array(ps), np.array(prose)
    brier = lambda q: float(((np.array(q) - ys) ** 2).mean())      # noqa: E731
    ece, table = engine.calibration(ys, ps)
    e1, _ = engine.calibration(ys[prose], ps[prose])
    e0, _ = engine.calibration(ys[~prose], ps[~prose])
    lines = ["# Evaluation", "",
             f"Generated by `python -m ca.evaluate` on {len(SEEDS)} synthetic court systems (seeds {SEEDS[0]} to {SEEDS[-1]}; 6,000 cases each) that the demo and the tests never use.",
             "Every outcome is drawn from a hidden model, so the estimates can be compared with the true probability, which no real court will ever supply.",
             "Read these as a check that the methods work, not as accuracy on real dockets.", "",
             "## 1. Motion-outcome model", "",
             f"Trained on motions decided before {world.SPLIT:%Y}; scored on the {len(ys):,} decided after ({ys.mean():.1%} granted).", "",
             "| | AUC | Brier score (lower is better) |", "|---|---|---|",
             f"| Logistic model: motion, suit, judge's shrunk record, outcomes in similar cases, four case features | {engine.auc(ys, ps):.3f} | {brier(ps):.4f} |",
             f"| Judge's shrunk grant rate for that motion alone | {engine.auc(ys, base_judge):.3f} | {brier(base_judge):.4f} |",
             f"| Judge's raw grant rate (no shrinkage) | {engine.auc(ys, raw_judge):.3f} | {brier(raw_judge):.4f} |",
             f"| Base rate for the motion type | {engine.auc(ys, base_type):.3f} | {brier(base_type):.4f} |",
             f"| The true probability (the ceiling: outcomes are coin flips around it) | {engine.auc(ys, truth_p):.3f} | {brier(truth_p):.4f} |", "",
             f"Calibration (expected calibration error {ece:.3f}):", "", "| Estimated chance | Motions | Mean estimate | Granted |", "|---|---|---|---|"]
    lines += [f"| {r['range']} | {r['n']:,} | {r['predicted']:.1%} | {r['observed']:.1%} |" for r in table]
    lines += ["", f"By group: calibration error {e1:.3f} for plaintiffs without a lawyer ({int(prose.sum()):,} motions) and {e0:.3f} for the rest.", "",
              f"The 80% interval around each estimate contained the true probability {cover[0] / cover[1]:.1%} of the time. It is not 80%: the model leaves out things the simulator uses (the strength of the claim, fact-pattern effects), and an interval built from resampling cannot know what the model is missing.", "",
              "## 2. Similar cases", "",
              "For 300 cases per court system: the ten nearest by TF-IDF cosine on the facts. A hit shares the hidden fact pattern.", "",
              "| | Share of the ten that share the fact pattern |", "|---|---|", f"| TF-IDF on the facts | {np.mean(sim):.1%} |", f"| Baseline: ten random cases with the same nature of suit | {np.mean(sim_base):.1%} |", "",
              "Facts are assembled from four sentences per pattern, so nearest neighbours are easy here. Real complaints are not written from a phrase bank.", "",
              "## 3. Citation treatment", "",
              f"Word n-gram TF-IDF + logistic regression over followed / distinguished / criticized / overruled, scored on {tm['model']['n_test']:,} sentences it was not fitted on.", "",
              "| | Accuracy |", "|---|---|", f"| Classifier | {tm['model']['accuracy']:.1%} |", f"| Baseline: keyword rules | {tm['baseline']['accuracy']:.1%} |", "",
              "The keyword rules are tripped by sentences such as \"The court does not follow X\" (distinguished) and \"cannot be followed\" (overruled).", "",
              "## 4. Time to resolution", "",
              "Median days from filing to closing by nature of suit, compared with the generator's true median. About 15% of cases are still open at the data cut.", "",
              "| | Mean error of the median |", "|---|---|", f"| Kaplan-Meier (open cases count for as long as they have been open) | {np.mean(km_err):.1%} |", f"| Baseline: median of closed cases only | {np.mean(naive_err):.1%} |"]
    out = pathlib.Path(__file__).resolve().parent.parent / "docs" / "evaluation.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
